export function getQualityTool(toolId) {
  return QUALITY_EXCELLENCE_TOOLS.find((t) => t.id === toolId) || null
}

export function getQualityToolsByStage(stageId) {
  return QUALITY_EXCELLENCE_TOOLS.filter((t) => t.stage === stageId)
}

export function blankTableRows(table) {
  const seed = Array.isArray(table.seed) ? table.seed : []
  const min = Math.max(table.minRows || 1, seed.length)
  const rows = []
  for (let i = 0; i < min; i += 1) {
    const row = { id: `row-${i + 1}` }
    table.columns.forEach((col) => { row[col.key] = '' })
    if (seed[i]) Object.assign(row, seed[i])
    rows.push(row)
  }
  return rows
}

export function createBlankQualityRecord(tool) {
  const fields = {}
  ;[...(tool.headerFields || []), ...(tool.fields || [])].forEach((field) => {
    fields[field.key] = field.key === 'status' ? 'draft' : field.key === 'date' ? new Date().toISOString().slice(0, 10) : ''
  })
  const tables = {}
  ;(tool.tables || []).forEach((table) => {
    tables[table.key] = blankTableRows(table)
  })
  return { fields, tables }
}
