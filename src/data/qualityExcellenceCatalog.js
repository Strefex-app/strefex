function tool(partial) {
  const stageMeta = QUALITY_EXCELLENCE_STAGES.find((s) => s.id === partial.stage)
  return {
    icon: 'quality',
    headerFields: HEADER_FIELDS,
    fields: [],
    tables: [],
    tag: stageMeta?.key || 'analysis',
    tagLabel: stageMeta?.label || 'Analysis',
    shortName: String(partial.name || '').split(/[—–]/)[0].trim(),
    ...partial,
  }
}

